export function coverFor(slug: string): Cover | undefined {
  const cover = covers[slug];
  if (!cover) return undefined;
  return {
    ...cover,
    src: `/work/covers/${slug}.webp`,
    width: WIDTH,
    height: HEIGHT,
  };
}

